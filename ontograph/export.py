"""Export knowledge graphs to various formats."""

from __future__ import annotations

import json
from pathlib import Path

import networkx as nx

from ontograph.graph import OntologyGraph
from ontograph.models import KnowledgeGraph


def export_induced_schema(
    entity_vocab: list[dict],
    relation_vocab: list[dict],
    name: str = "induced",
) -> str:
    """Serialise an LLM-induced vocabulary to a YAML schema file.

    The output is a valid ontograph schema that can be passed to future
    ingest runs via --schema, allowing the discovered vocabulary to be
    reused without re-running consolidation.
    """
    try:
        import yaml
    except ImportError:
        raise ImportError("PyYAML required: uv add pyyaml")

    entity_types: dict = {}
    for item in entity_vocab:
        t = item.get("type", "").strip()
        if not t:
            continue
        entity_types[t] = {
            "description": item.get("description", ""),
            "subtypes": [],
        }

    relation_types: dict = {}
    for item in relation_vocab:
        t = item.get("type", "").strip()
        if not t:
            continue
        relation_types[t] = {
            "description": item.get("description", ""),
        }

    schema_dict = {
        "name": name,
        "version": "1.0",
        "description": "Inductively discovered schema — generated by ontograph schema-free extraction",
        "entity_types": entity_types,
        "relation_types": relation_types,
    }

    return yaml.dump(schema_dict, default_flow_style=False, sort_keys=False, allow_unicode=True)


def export_json(graph: OntologyGraph, path: str | Path) -> None:
    """Export as JSON (canonical portable format)."""
    kg = graph.to_kg()
    Path(path).write_text(kg.to_json(), encoding="utf-8")


def export_graphml(graph: OntologyGraph, path: str | Path) -> None:
    """Export as GraphML (compatible with Gephi, yEd, Cytoscape desktop)."""
    nx.write_graphml(graph.g, str(path))


def export_mermaid(graph: OntologyGraph) -> str:
    """Export as Mermaid diagram text."""
    lines = ["graph LR"]
    # Node definitions with type labels
    for name, data in graph.g.nodes(data=True):
        etype = data.get("entity_type", "concept")
        safe = name.replace(" ", "_").replace('"', "'")
        lines.append(f'    {safe}["{name}<br/><i>{etype}</i>"]')

    # Edge definitions
    for u, v, data in graph.g.edges(data=True):
        rtype = data.get("relation_type", "relates_to")
        safe_u = u.replace(" ", "_").replace('"', "'")
        safe_v = v.replace(" ", "_").replace('"', "'")
        lines.append(f'    {safe_u} -->|{rtype}| {safe_v}')

    return "\n".join(lines)


def export_obsidian_canvas(graph: OntologyGraph) -> str:
    """Export as Obsidian Canvas JSON (.canvas) for native Obsidian graph view."""
    import math

    nodes_list = list(graph._entities.keys())
    n = len(nodes_list)

    # Arrange nodes in a spiral grid layout
    canvas_nodes = []
    cols = max(1, math.ceil(math.sqrt(n)))
    node_w, node_h, gap = 200, 80, 40

    for i, name in enumerate(nodes_list):
        entity = graph._entities[name]
        col = i % cols
        row = i // cols
        x = col * (node_w + gap)
        y = row * (node_h + gap)
        etype = entity.entity_type
        obs = entity.observations
        text = f"**{name}**\n_{etype}_"
        if obs:
            text += "\n\n" + "\n".join(f"- {o}" for o in obs[:3])
        canvas_nodes.append({
            "id": name,
            "type": "text",
            "text": text,
            "x": x,
            "y": y,
            "width": node_w,
            "height": node_h + (len(obs[:3]) * 20 if obs else 0),
        })

    canvas_edges = []
    for i, (u, v, data) in enumerate(graph.g.edges(data=True)):
        canvas_edges.append({
            "id": f"e{i}",
            "fromNode": u,
            "toNode": v,
            "fromSide": "right",
            "toSide": "left",
            "label": data.get("relation_type", "").replace("_", " "),
        })

    doc = {"nodes": canvas_nodes, "edges": canvas_edges}
    return json.dumps(doc, indent=2)


def export_jsonld(graph: OntologyGraph) -> str:
    """Export as JSON-LD (linked data format)."""
    context = {
        "@context": {
            "ontograph": "https://github.com/murzua7/ontograph/schema#",
            "name": "ontograph:name",
            "type": "ontograph:entityType",
            "source": "ontograph:source",
            "target": "ontograph:target",
            "relationType": "ontograph:relationType",
        }
    }

    entities = []
    for name, entity in graph._entities.items():
        entities.append({
            "@id": f"ontograph:entity/{entity.id}",
            "name": name,
            "type": entity.entity_type,
            "observations": entity.observations,
        })

    relations = []
    for u, v, data in graph.g.edges(data=True):
        relations.append({
            "source": u,
            "target": v,
            "relationType": data.get("relation_type", "relates_to"),
        })

    doc = {
        **context,
        "entities": entities,
        "relations": relations,
    }
    return json.dumps(doc, indent=2)
